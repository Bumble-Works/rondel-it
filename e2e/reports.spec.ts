test('keeps Custom date fields beneath the selector in a narrow window', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await openSeededReports(page)
  const period = page.getByRole('combobox', { name: 'Period', exact: true })
  await period.selectOption('custom')
  const from = page.getByLabel('From', { exact: true })
  const through = page.getByLabel('Through', { exact: true })
  await expect(from).toBeVisible()
  await expect(through).toBeVisible()
  const selectorBox = await period.boundingBox()
  const inputBox = await from.boundingBox()
  expect(selectorBox).not.toBeNull()
  expect(inputBox).not.toBeNull()
  expect(inputBox!.y).toBeGreaterThanOrEqual(selectorBox!.y + selectorBox!.height)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
